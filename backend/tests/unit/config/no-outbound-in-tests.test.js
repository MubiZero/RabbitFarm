const CONFIGS = {
  'SMS-шлюз (payom)': require('../../../src/config/payom'),
  'почта (SMTP)': require('../../../src/config/mailer'),
  'платежи (Эсхата)': require('../../../src/config/eskhata'),
  'пуши (Firebase)': require('../../../src/config/firebase'),
  'оповещения (Telegram)': require('../../../src/config/telegram'),
  'Sentry': require('../../../src/config/sentry'),
  'кэш (Redis)': require('../../../src/config/redis')
};

/**
 * Тесты наружу не ходят.
 *
 * `dotenv` подтягивает `backend/.env` и в тестах, а у разработчика там
 * боевые ключи шлюзов. Регистрация по телефону ждёт отправку кода, не
 * отпуская ответ (`otpAuthService`), — и набор начинал зависеть от того,
 * отвечает ли сейчас gateway.payom.tj. Замерено на `auth.test.js`: 1,6 с при
 * живом шлюзе, 22 с при недоступном; в полном прогоне отдельные файлы
 * растягивались до 900 секунд и падали по 60-секундному пределу jest целиком.
 * В CI этих переменных нет, поэтому сборка была зелёной, а флак жил только на
 * машинах разработчиков — и выглядел как случайная порча тестов.
 *
 * Гасит их `tests/setup.js`. Этот сторож нужен затем, что обратная поломка
 * беззвучна: вернувшийся ключ ничего не сломает сразу, он просто однажды
 * уронит чужой прогон, когда моргнёт сеть.
 */
describe('Внешние шлюзы в тестах', () => {
  for (const [name, config] of Object.entries(CONFIGS)) {
    it(`${name} не настроен — обращение откажет, не трогая сеть`, () => {
      expect(config.isConfigured).toBe(false);
    });
  }
});
