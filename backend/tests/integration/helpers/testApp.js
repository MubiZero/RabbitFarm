process.env.NODE_ENV = 'test';

const app = require('../../../src/app');

/**
 * Приложение, уже слушающее на 127.0.0.1.
 *
 * Отдаём supertest готовый сервер, а не голое приложение, ради адреса.
 * Иначе supertest на каждый запрос поднимает свой: `app.listen(0)` без
 * адреса — то есть `0.0.0.0` и порт из эфемерного диапазона (на macOS
 * 49152–65535), — а ходит потом на `127.0.0.1`. Это разные привязки, и
 * система спокойно выдаёт тесту порт, уже занятый кем-то на самом
 * `127.0.0.1`: у docker-машины (Lima) там висит SSH-проброс. Соединение
 * уходит по более точному совпадению — в чужой SSH, клиент читает
 * `SSH-2.0-OpenSSH_...` вместо ответа и падает с
 * `Parse Error: Expected HTTP/, RTSP/ or ICE/`.
 *
 * Выглядело это как случайный флак: раз в несколько прогонов рушился один
 * тест или целый файл, всегда по-разному, и только на машинах
 * разработчиков — в CI нет ни Lima, ни её проброса.
 *
 * Привязка к `127.0.0.1` закрывает дыру в корне: теперь система знает, что
 * занятый на этом адресе порт выдавать нельзя. Заодно на прогон приходится
 * 44 слушателя вместо примерно семисот.
 */
const server = app.listen(0, '127.0.0.1');

// `listen` с адресом поднимается не сразу: Node сначала разрешает хост, и
// привязка происходит на следующем обороте цикла. Без этого ожидания
// supertest успевал увидеть `address() === null` и поднимал свой сервер —
// ровно тот, от которого мы уходим.
beforeAll((done) => {
  if (server.listening) return done();
  server.once('listening', () => done());
  server.once('error', done);
});

// Тело в скобках, а не стрелка-выражение: `server.close(done)` возвращает
// сам сервер, а jest запрещает разом и `done`, и возвращаемое значение.
afterAll((done) => {
  server.close(() => done());
});

module.exports = server;
