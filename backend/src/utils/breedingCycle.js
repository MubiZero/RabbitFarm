/**
 * Сроки цикла размножения — в одном месте.
 *
 * Раньше 31 и 28 стояли числами прямо в коде, и каждая копия жила своей
 * жизнью: задача «поставить маточник» заводилась на 28-й день после случки
 * (за трое суток до окрола), а пуш с тем же смыслом предупреждал за двое.
 * Человек получал напоминание позже, чем задачу, о том же самом — и день
 * расходился ещё и с планом, который вешают в сарае на гвоздь.
 */

/** Сукрольность: от случки до окрола. */
const GESTATION_DAYS = 31;

/**
 * День после случки, когда в клетку ставят маточник.
 *
 * Не «в день окрола»: гнездо нужно самке заранее, она его обустраивает и
 * выщипывает пух. Поставленное в день окрола — уже поздно, крольчата
 * рождаются на сетку и гибнут.
 */
const NEST_BOX_DAY = 28;

/** За сколько суток до окрола нужен маточник. */
const NEST_BOX_BEFORE_BIRTH = GESTATION_DAYS - NEST_BOX_DAY;

module.exports = { GESTATION_DAYS, NEST_BOX_DAY, NEST_BOX_BEFORE_BIRTH };
