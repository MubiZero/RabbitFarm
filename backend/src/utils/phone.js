/**
 * Телефон в таджикском виде — `+992XXXXXXXXX`.
 *
 * Формат задан не нами: шлюз Payom принимает номер строго с плюсом и кодом
 * страны, на всё остальное отвечает 422 (живая проверка 2026-09-07, см.
 * docs/ENVIRONMENT.md). Раз номер всё равно приходится приводить к одному виду
 * перед отправкой, правило живёт здесь одно на всех, а не переписывается
 * в каждом валидаторе.
 *
 * Общий международный regex из `authValidator`/модели `User` этому не
 * равен — он пропускает и номер без кода страны, и запись через 8. Перевод
 * регистрации и профиля на этот формат отдельная работа: там уже лежат
 * номера, записанные по старому правилу, и их придётся переносить.
 */

const TJ_PHONE_PATTERN = /^\+992\d{9}$/;

/**
 * Привести номер к `+992XXXXXXXXX`, если он узнаётся.
 *
 * Человек пишет номер как ему удобно — «+992 90 123 45 67», «992901234567»,
 * «901234567». Разделители убираем, недостающий код страны подставляем.
 * Годность решает вызывающий (валидатор): номер, который не разобрался,
 * возвращается как есть, а не молча превращается в чужой.
 */
const normalizeTjPhone = (value) => {
  if (typeof value !== 'string') return value;

  const digits = value.replace(/[^\d]/g, '');

  if (digits.length === 9) return `+992${digits}`;
  if (digits.length === 12 && digits.startsWith('992')) return `+${digits}`;

  return value.trim();
};

const isTjPhone = (value) => TJ_PHONE_PATTERN.test(value);

module.exports = { TJ_PHONE_PATTERN, normalizeTjPhone, isTjPhone };
