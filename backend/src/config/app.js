require('dotenv').config();

/**
 * Публичный адрес приложения — тот, что мы даём людям наружу.
 *
 * `/i` — страница приглашения: на телефоне с установленным приложением её
 * перехватывает само приложение (Universal Links на iOS, App Links на
 * Android), без приложения открывается страница со ссылками на магазины и
 * веб-версию. Один и тот же адрес на всех трёх стадиях — до публикации в
 * магазинах, после неё и после проверки ссылок доменом.
 *
 * Адрес уходит в письмо с приглашением и возвращается владельцу в ответе
 * `POST /staff/invitations`, откуда тот пересылает его работнику. В SMS
 * ссылка не уходит: единственный одобренный шаблон payom это код входа
 * («{text-1} - код подтверждения: {code-1}»), ссылки в нём нет, и смена
 * домена модерации не требует.
 *
 * Но приглашение живёт в переписке дольше, чем переезд: адрес, уже
 * отправленный людям, обязан продолжать работать. Прежний домен поэтому не
 * выключается, а приложение узнаёт оба (см. mobile/lib/core/router/deep_links.dart).
 */
const publicUrl = (process.env.APP_PUBLIC_URL || 'https://rabbitfarm.mubi.dev').replace(/\/+$/, '');

module.exports = {
  publicUrl,
  inviteUrl: `${publicUrl}/i`
};
