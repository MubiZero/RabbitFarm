const express = require('express');
const router = express.Router();
const { COUNTRIES } = require('../config/countries');
const ApiResponse = require('../utils/apiResponse');

/**
 * Справочник стран — публично, без входа.
 *
 * Страну спрашивают в знакомстве, до регистрации, поэтому запросить её
 * список можно без токена. Отдаём именно то, от чего зависит поведение
 * экранов: валюту, пояс, доходит ли СМС и принимаем ли мы здесь оплату
 * картой. Названия стран лежат в переводах приложения — переводить их на
 * сервере значило бы держать четыре словаря в двух местах сразу.
 *
 * Клиент носит с собой такой же список на случай первого запуска без сети;
 * паритет кодов сторожит тест, чтобы два списка не разъехались.
 */
router.get('/', (req, res) =>
  ApiResponse.success(res, { countries: Object.values(COUNTRIES) })
);

module.exports = router;
