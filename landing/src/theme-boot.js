/*
 * Тема до первой отрисовки.
 *
 * Отдельный файл, а не пара строк в самой странице: инлайн-скрипт не
 * пропустит CSP (см. nginx.conf). Подключён в <head> без defer намеренно —
 * он должен отработать раньше, чем браузер нарисует первый кадр, иначе
 * выбранная тема применяется вспышкой поверх системной.
 */
(function () {
  'use strict';
  try {
    var saved = localStorage.getItem('theme');
    if (saved === 'light' || saved === 'dark') {
      document.documentElement.dataset.theme = saved;
    }
  } catch (e) {
    /* Приватный режим: остаётся тема телефона, и это нормально. */
  }
})();
