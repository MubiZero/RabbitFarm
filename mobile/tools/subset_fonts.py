# -*- coding: utf-8 -*-
"""Обрезает Inter до знаков, которые приложение действительно показывает.

Зачем: полный Inter — это 2857 знаков и 400 КБ на каждое начертание, то есть
1,6 МБ на первый запуск. Фермер открывает приложение на дешёвом телефоне и
медленной сети, и почти весь этот вес — письменности, которых он никогда не
увидит: греческая, вьетнамская, деванагари.

Почему нельзя просто взять woff2, как на витрине: витрину рисует браузер, а
приложение — CanvasKit, и шрифт он читает сам, без CSS. Сжатые woff2 он не
понимает, поэтому вес снимаем обрезкой, а сжатие включено на раздаче
(`nginx.conf`, gzip для `font/ttf`).

Чего здесь нет намеренно: знаков, которые фермер вводит сам (клички, заметки
на другом языке). Их движок догрузит запасным шрифтом — редкий случай не
стоит того, чтобы носить с собой всю таблицу Юникода.

Запуск (нужны `pip install fonttools brotli`):

    python tools/subset_fonts.py

Скрипт перезаписывает `fonts/Inter-*.ttf` обрезанными версиями. Исходные
файлы всегда можно взять заново с rsms.me/inter.

Ещё 50 КБ на начертание снимает `--no-hinting`: инструкции хинтинга Flutter
не исполняет, рисует Skia по-своему. Не сделано, потому что проверить это
глазами на дешёвом Android в тот день было не на чем, а текст под солнцем
дороже двухсот килобайт.
"""
import pathlib
import subprocess
import sys

FONTS = pathlib.Path(__file__).resolve().parent.parent / 'fonts'

# Диапазоны с запасом: обрезка ради килобайтов не должна оборачиваться
# пустыми квадратами в интерфейсе.
RANGES = [
    'U+0000-00FF',   # латиница и знаки препинания
    'U+0100-017F',   # латиница расширенная A (ō, ş)
    'U+0180-024F',   # латиница расширенная B (ǵ)
    'U+02B0-02FF',   # модификаторы: узбекские oʻ и gʻ
    'U+0300-036F',   # комбинируемые надстрочные
    'U+0400-04FF',   # кириллица: русский и таджикский
    'U+0500-052F',   # кириллица дополнительная
    'U+2000-206F',   # тире, кавычки, неразрывный пробел
    'U+20A0-20BF',   # знаки валют: ₸, ₽
    'U+2100-214F',   # №
    'U+2190-21BB',   # стрелки
    'U+2200-22FF',   # ≥, ≤, ×
    'U+FEFF',        # маркер порядка байтов
]


def main() -> int:
    files = sorted(FONTS.glob('Inter-*.ttf'))
    if not files:
        print('шрифты не найдены:', FONTS)
        return 1

    for font in files:
        before = font.stat().st_size
        subprocess.run(
            [
                sys.executable, '-m', 'fontTools.subset', str(font),
                '--unicodes=' + ','.join(RANGES),
                # Оставляем только то, что нужно обычному тексту: кернинг,
                # лигатуры, местные формы, моноширинные цифры. Остальные
                # таблицы Inter (восемь стилистических наборов, дроби,
                # старостильные цифры) приложение не включает никогда, а
                # весят они треть файла.
                '--layout-features=kern,liga,clig,calt,ccmp,mark,mkmk,locl,tnum',
                '--notdef-outline',
                '--output-file=' + str(font),
            ],
            check=True,
        )
        after = font.stat().st_size
        print('%-28s %6d КБ -> %4d КБ' % (font.name, before // 1024, after // 1024))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
