/// Design token: размеры того, во что человек попадает пальцем.
///
/// Обычные рекомендации платформ (44pt у iOS, 48dp у Android) написаны про
/// телефон в тёплой комнате и голый палец. Здесь работают иначе: кроликов
/// отмечают в сарае, зимой, в рабочих перчатках, часто одной рукой — второй
/// придерживают клетку или животное. Промах в таких условиях стоит не
/// «нажму ещё раз», а «запишу потом» — то есть не запишу.
///
/// Поэтому шкала поднята: исследования полевых интерфейсов (Zebra и другие
/// производители промышленных терминалов) сходятся на +25% к потребительской
/// норме, то есть 56–64.
abstract class AppSizes {
  /// Нижняя граница для всего нажимаемого: строк списка, значков-кнопок,
  /// переключателей. Ниже опускаться нельзя.
  static const double touchTarget = 56;

  /// Главное действие экрана — кнопка внизу формы, «Сохранить», «Отметить».
  /// Промах по ней дороже всего: человек теряет не шаг, а всю запись.
  static const double touchTargetLarge = 64;

  /// Значок-кнопка в шапке или в строке (`IconButton`). Сама иконка меньше,
  /// но область нажатия — эта.
  static const double iconButton = 56;
}
