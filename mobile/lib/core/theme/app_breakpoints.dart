import 'package:flutter/widgets.dart';

/// Design token: где мобильная (списки-карточки) раскладка уступает место
/// более плотной, «настольной».
///
/// Приложение не адаптивное почти нигде — оно мобильное по духу, и это
/// осознанный выбор. Единственное системное исключение — платформенная
/// админка: `rabbitfarm-web` открывает её же в браузере на большом экране
/// (см. docs/plans/PLATFORM-ADMIN.md), и там, где строк много, а колонок
/// хочется сравнивать взглядом (список ферм), карточка в один столбец —
/// не формат. Не тянуть этот брейкпоинт на остальные экраны, пока для них
/// не появится такая же причина.
abstract class AppBreakpoints {
  /// От этой ширины экран платформенной админки переключается на табличный
  /// вид. Ниже — обычные карточки, как и везде в приложении.
  static const double wideScreen = 900;
}

extension AppBreakpointsContext on BuildContext {
  /// `true`, если ширина окна укладывается в «настольную» раскладку.
  bool get isWideScreen =>
      MediaQuery.sizeOf(this).width >= AppBreakpoints.wideScreen;
}
