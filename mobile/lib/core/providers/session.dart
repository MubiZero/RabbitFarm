import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_riverpod/legacy.dart';

/// Номер текущей сессии.
///
/// Провайдеры репозиториев наблюдают за ним, поэтому увеличение номера
/// пересоздаёт их — а вместе с ними и все списки, карточки и сводки, которые от
/// них зависят. Без этого при выходе очищалось только состояние авторизации, а
/// данные оставались в памяти: на общем планшете фермы следующий вошедший видел
/// поголовье, клетки и породы предыдущего, причём без единого запроса к серверу.
///
/// Провайдер авторизации намеренно за ним не следит: иначе он пересоздавал бы
/// сам себя в момент выхода.
final sessionRevisionProvider = StateProvider<int>((ref) => 0);

/// Забыть данные предыдущего пользователя.
void resetSessionData(Ref ref) {
  ref.read(sessionRevisionProvider.notifier).state++;
}
