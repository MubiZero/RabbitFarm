import 'package:printing/printing.dart';

/// Напечатать лист, собранный разметкой.
///
/// Документ строится HTML, а не виджетами пакета `pdf`: его встроенные
/// шрифты кириллицы не содержат, и клички кроликов ушли бы на бумагу
/// пустыми прямоугольниками. Бандлить ради этого шрифт значит возить с
/// приложением несколько мегабайт; разметку же в PDF переводит сама
/// платформа — со всеми алфавитами, которые на телефоне уже есть.
///
/// Одна точка на всё приложение: и план окролов, и метки на клетки
/// печатаются отсюда, иначе устаревший вызов и пояснение к нему пришлось бы
/// повторять в каждом месте печати.
Future<void> printHtmlSheet({
  required String html,
  required String documentName,
}) =>
    Printing.layoutPdf(
      name: documentName,
      // Замены этому способу у пакета нет: всё, что он предлагает взамен, —
      // собирать документ его же виджетами, то есть вернуться к проблеме
      // шрифтов.
      // ignore: deprecated_member_use
      onLayout: (format) => Printing.convertHtml(format: format, html: html),
    );
