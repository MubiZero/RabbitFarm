import 'package:flutter/widgets.dart';

/// Локаль для `intl`-форматирования дат (`DateFormat`, `showDatePicker`).
///
/// Пакет `intl` знает календарные названия месяцев и дней для русского,
/// узбекского и английского, но не для таджикского — данных `tg` в его
/// CLDR-таблицах попросту нет. Ближайший осмысленный вариант — русские
/// названия: в Таджикистане даты в документах и объявлениях без родного
/// перевода принято показывать именно на русском, а не на английском.
String dateSymbolsLocale(Locale appLocale) =>
    appLocale.languageCode == 'tg' ? 'ru' : appLocale.languageCode;
