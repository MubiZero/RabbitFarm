import 'package:flutter/widgets.dart';

/// Локаль для `intl`-форматирования дат (`DateFormat`, `showDatePicker`).
///
/// Пакет `intl` знает календарные названия месяцев и дней для русского,
/// узбекского и английского, но не для таджикского — данных `tg` в его
/// CLDR-таблицах попросту нет, и раньше таджикский экран показывал русские
/// месяцы. Теперь таджикский календарь заводим сами
/// (`core/l10n/tajik_dates.dart`), поэтому язык здесь возвращается как есть.
String dateSymbolsLocale(Locale appLocale) => appLocale.languageCode;

/// То же самое по контексту экрана — короткая форма для мест, где даты
/// показываются человеку.
///
/// Локаль передаётся явно, а не через `Intl.defaultLocale`: глобальная
/// подстройка в `main.dart` остаётся страховкой для кода, до которого
/// контекст не доезжает, но экран обязан знать язык читателя сам — иначе
/// в тестах и в любом дереве без `MyApp` даты молча уезжают в чужой язык.
String dateLocaleOf(BuildContext context) =>
    dateSymbolsLocale(Localizations.localeOf(context));
