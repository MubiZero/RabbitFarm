/// Таблица, которую откроют в Excel.
///
/// Три решения, от которых зависит, увидит ли человек таблицу или кашу:
///
/// * **Разделитель — точка с запятой.** Excel с русской, таджикской и
///   узбекской региональной настройкой ждёт именно её; файл с запятыми он
///   сваливает целиком в первый столбец.
/// * **Десятичная запятая.** В тех же настройках «2.5» с точкой Excel
///   считает текстом, и столбец с весом или суммой перестаёт складываться.
/// * **BOM в начале файла.** Без него Excel читает кириллицу как
///   «Ð¡Ð°Ñ„Ð°Ñ€» — открыть такой файл человек сможет, прочитать нет.
///
/// Файл собирается строкой целиком: выгрузки здесь размером в сотни строк,
/// а не в миллионы, и городить потоковую запись незачем.
library;

const _separator = ';';

/// `\r\n`, а не `\n`: этого требует сам формат (RFC 4180), и старые версии
/// Excel на «голом» переводе строки склеивают строки таблицы.
const _lineBreak = '\r\n';

/// Знак порядка байтов. Excel по нему понимает, что файл в UTF-8.
const _bom = '﻿';

/// Собрать CSV из строк таблицы. Первая строка — заголовки.
String buildCsv(List<List<String>> rows) {
  final buffer = StringBuffer(_bom);
  for (final row in rows) {
    buffer.write(row.map(_cell).join(_separator));
    buffer.write(_lineBreak);
  }
  return buffer.toString();
}

/// Кавычки нужны, когда внутри значения есть разделитель, кавычка или перевод
/// строки: заметка «Вялость, отказ от корма» без них разъехалась бы на два
/// столбца.
String _cell(String value) {
  final needsQuotes = value.contains(_separator) ||
      value.contains('"') ||
      value.contains('\n') ||
      value.contains('\r');
  if (!needsQuotes) return value;
  return '"${value.replaceAll('"', '""')}"';
}

/// Число для таблицы: с запятой и без хвоста из нулей.
///
/// «4,20 кг» на листе читается как измеренная точность, которой в данных нет,
/// а «120,50» рядом с «450» выглядит разнобоем. Лишние нули убираются, но
/// значащие остаются: «120,05» так и останется.
String csvNumber(num? value, {int decimals = 2}) {
  if (value == null) return '';

  var text = value.toStringAsFixed(decimals);
  if (text.contains('.')) {
    text = text.replaceAll(RegExp(r'0+$'), '');
    text = text.replaceAll(RegExp(r'\.$'), '');
  }
  return text.replaceAll('.', ',');
}
